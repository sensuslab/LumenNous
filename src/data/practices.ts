function buildPractices(): Practice[] {
  const practices: Practice[] = [];
  for (const [categoryId, defs] of Object.entries(DEFS)) {
    defs.forEach((def, index) => {
      const record: Record<string, unknown> = {
        id: `prc-${categoryId}-${String(index + 1).padStart(2, "0")}`,
        slug: def.slug,
        title: def.title,
        practiceType: def.practiceType,
        categoryIds: expandCorpusCategoryIds([categoryId]),
        durationOptions: def.durationOptions,
        preparation: def.preparation,
        steps: def.steps,
        closing: def.closing,
        accessibilityNotes: def.accessibilityNotes,
        safetyNotes: def.safetyNotes,
        sourceIds: def.sourceIds,
        audioIds: [],
        editorialStatus: "draft",
      };
      practices.push(PracticeSchema.parse(record));
    });
  }
  return [
    ...practices,
    ...corpusSeedPractices.map((practice) =>
      PracticeSchema.parse({
        ...practice,
        categoryIds: expandCorpusCategoryIds(practice.categoryIds),
      }),
    ),
  ];
}

// Validated at module load — a malformed practice fails the build/tests.
export const practices: Practice[] = buildPractices();

export const practiceById = new Map(practices.map((practice) => [practice.id, practice]));
export const practiceBySlug = new Map(
  practices.map((practice) => [practice.slug, practice]),
);
